"""Build bundled, entirely fictional DOCX/PDF/PNG examples for resume templates."""
from __future__ import annotations

import importlib.util
import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
EXPORTER = ROOT / ".agents/skills/document-export/scripts/export_documents.py"
OUT = ROOT / "docs/assets/resume-templates"
SPEC = importlib.util.spec_from_file_location("oriward_document_export", EXPORTER)
exporter = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(exporter)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replace", action="store_true", help="replace samples previously generated by this script")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    isolated = tempfile.TemporaryDirectory(prefix="oriward-template-samples-")
    os.environ["ORIWARD_DB"] = str(Path(isolated.name) / "sample.sqlite3")
    os.environ["ORIWARD_OUTPUT_DIR"] = str(Path(isolated.name) / "resumes")
    from oriward import services, sources
    services.save_profile({"display_name": "林青", "contact": {"email": "fictional@example.test"},
        "summary_verified": "虚构大学统计学专业应届毕业生，预计2026年毕业。熟悉 Python、Excel 数据处理，关注从数据清理到业务表达的完整流程。"})
    experience_ids = []
    examples = [
        ("校园出行问卷分析", ["整理虚构问卷样例，记录缺失值和异常值处理方法。",
            "使用 Python 清理字段并比较不同年级的出行方式分布。",
            "制作图表并说明样本范围与结论限制。"]),
        ("课程图书借阅观察", ["把虚构借阅记录整理为统一字段并保留原始数据副本。",
            "用 Excel 数据透视表核对分类汇总结果。",
            "撰写简短说明，区分观察到的现象与可能原因。"]),
    ]
    for event, actions in examples:
        experience_ids.append(services.add_object("experiences", {
            "event": event, "actions": actions, "outcomes": [],
            "evidence": [{"claim": "课程项目内容", "source": "fictional sample", "status": "user_confirmed"}],
            "approved_for_resume": True}, ["event", "actions", "outcomes", "evidence", "approved_for_resume"]))
    job_id = sources.import_records([{"source": "fictional sample", "source_id": "resume-template",
        "title": "数据分析实习生", "company": "虚构示例公司", "description": "格式样本", "url": "https://example.invalid/sample"}])["job_ids"][0]
    resume = services.build_resume(job_id, experience_ids, headline="数据分析方向")
    resume_id = resume["id"]
    resume_path = Path(resume["path"])
    content = resume_path.read_text(encoding="utf-8")
    content = content.replace("## 相关经历", "## 教育经历\n\n虚构大学 | 统计学学士 | 2022.09 - 2026.06\n课程：概率统计、数据库基础、应用回归\n\n## 项目经历", 1)
    content = content.replace("*申请方向：数据分析方向*", "")
    marker = "---\n\n*来源记录："
    content = content.replace(marker, "## 技能\n\n- Python 数据清洗、分组汇总与图表制作\n- Excel 数据透视表与数据核对\n- 结果说明与分析限制表达\n\n## 兴趣\n\n- 徒步\n\n" + marker)
    resume_path.write_text(content, encoding="utf-8")
    normalized, _ = exporter._load_resume(resume_id)
    font = None
    try:
        font = str(exporter._choose_font(exporter._all_text(normalized), None,
                                        require_pdf=True))
    except exporter.ExportError as exc:
        raise SystemExit(f"A local embeddable Chinese font is required: {exc}")
    for template in exporter.TEMPLATES:
        target = OUT / template
        if target.exists():
            manifest_path = target / "manifest.json"
            try:
                old_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                old_manifest = {}
            if not args.replace or old_manifest.get("fictional") is not True or \
                    old_manifest.get("source") != "scripts/generate_template_samples.py":
                raise SystemExit(f"Sample target exists or is not owned by this generator: {target}; use --replace only for owned samples")
            for filename in ("manifest.json", "preview.png", "sample.docx", "sample.pdf", "synthetic-portrait.png"):
                (target / filename).unlink(missing_ok=True)
            if (target / "export").exists():
                raise SystemExit(f"Unexpected export directory in sample target: {target / 'export'}")
        else:
            target.mkdir()
        portrait = target / "synthetic-portrait.png"
        if template == "modern-cn":
            canvas = Image.new("RGB", (260, 350), "#E9EFEC")
            draw = ImageDraw.Draw(canvas)
            draw.ellipse((77, 42, 183, 148), fill="#BE8F72")
            draw.pieslice((66, 30, 194, 166), 180, 360, fill="#354B4A")
            draw.rectangle((103, 139, 157, 213), fill="#BE8F72")
            draw.pieslice((27, 178, 233, 390), 180, 360, fill="#52766E")
            draw.rectangle((27, 278, 233, 350), fill="#52766E")
            canvas.save(portrait)
        exporter.export_document(resume_id=resume_id, output_dir=target / "export", template=template,
                                 font=font, renderer="auto", photo=portrait if template == "modern-cn" else None)
        for fmt in ("docx", "pdf"):
            (target / f"sample.{fmt}").write_bytes((target / "export" / f"document.{fmt}").read_bytes())
        pdf = target / "sample.pdf"
        converter = shutil.which("pdftoppm")
        if not converter:
            raise SystemExit("pdftoppm is required to generate preview PNGs")
        subprocess.run([converter, "-png", "-f", "1", "-singlefile", str(pdf), str(target / "preview")], check=True)
        export_manifest = json.loads((target / "export" / "manifest.json").read_text(encoding="utf-8"))
        (target / "manifest.json").write_text(json.dumps({"fictional": True, "template": template,
            "photo_included": template == "modern-cn", "synthetic_portrait": template == "modern-cn",
            "renderer": export_manifest["renderer"]["pdf"], "source": "scripts/generate_template_samples.py"}, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
        for artifact in (target / "export" / "document.docx", target / "export" / "document.pdf",
                         target / "export" / "manifest.json"):
            artifact.unlink(missing_ok=True)
        (target / "export").rmdir()
    print(OUT)
    isolated.cleanup()


if __name__ == "__main__":
    main()
